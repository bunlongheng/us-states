// Precompute the US map as static SVG path strings so the app renders it without
// react-simple-maps or d3 at runtime (kills ~80KB of JS + the projection TBT).
// Matches react-simple-maps' ComposableMap defaults exactly: 800x600 viewport,
// geoAlbersUsa().translate([400,300]).scale(900).
//
// Regenerate with: node scripts/gen-map-paths.mjs   (needs devDeps d3-geo + topojson-client)
import { readFileSync, writeFileSync } from "node:fs";
import { geoAlbersUsa, geoPath } from "d3-geo";
import { feature } from "topojson-client";

const topo = JSON.parse(readFileSync(new URL("./states-10m.json", import.meta.url)));
const fc = feature(topo, topo.objects.states);

const projection = geoAlbersUsa().translate([400, 300]).scale(900);
// 1 decimal is sub-pixel in an 800x600 viewport - drops the file ~65% with no visible change.
const path = geoPath(projection).digits(1);

const paths = fc.features
  .map((f) => {
    const [cx, cy] = path.centroid(f);
    return {
      fips: String(f.id).padStart(2, "0"),
      d: path(f) ?? "",
      cx: Math.round(cx * 100) / 100,
      cy: Math.round(cy * 100) / 100,
    };
  })
  .filter((p) => p.d);

const out =
  "// AUTO-GENERATED by scripts/gen-map-paths.mjs - do not edit by hand.\n" +
  "// Precomputed geoAlbersUsa (800x600, scale 900) SVG paths for the US states, so the\n" +
  "// map renders as plain SVG with no react-simple-maps / d3 in the client bundle.\n\n" +
  'export const MAP_VIEWBOX = "0 0 800 600";\n\n' +
  "export interface StatePath {\n  fips: string;\n  d: string;\n  cx: number;\n  cy: number;\n}\n\n" +
  "export const STATE_PATHS: StatePath[] = " +
  JSON.stringify(paths) +
  ";\n";

writeFileSync(new URL("../lib/mapPaths.ts", import.meta.url), out);
console.log(`wrote lib/mapPaths.ts with ${paths.length} state paths`);
